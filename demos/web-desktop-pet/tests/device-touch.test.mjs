import assert from 'node:assert/strict'
import test from 'node:test'
import { TouchAttention, TouchReplyGate } from '../electron/device-touch.mjs'

test('touch replies settle after release, merge gestures and drop cooldown/cancelled events', () => {
  const gate = new TouchReplyGate()
  gate.finish(true, 0)
  assert.equal(gate.take(549), false)
  gate.cancel()
  gate.finish(true, 300)
  assert.equal(gate.take(550), false)
  assert.equal(gate.take(850), true)
  assert.equal(gate.take(851), false)
  gate.finish(true, 1000)
  assert.equal(gate.take(6000), false, 'Cooldown gestures must not be queued for later')
  gate.finish(false, 6000)
  assert.equal(gate.take(7000), false, 'Unknown or cancelled gestures do not request replies')
  gate.finish(true, 7000)
  gate.cancel()
  assert.equal(gate.take(8000), false)
})

test('completed gestures include bounded portrait coordinates for a nose tap and a stroke path', () => {
  const touch = new TouchAttention()
  touch.begin(150, 180, 300, 360, 0)
  touch.move(150, 180, 100)
  assert.equal(touch.gesture(100).gesture_type, 'TAP')
  assert.deepEqual(touch.gesture(100).end_position, { x: 0.5, y: 0.5 })
  touch.begin(210, 180, 300, 360, 200)
  touch.move(180, 180, 350)
  touch.move(90, 180, 700)
  const gesture = touch.gesture(700)
  assert.equal(gesture.gesture_type, 'SWIPE_LEFT')
  assert.deepEqual(gesture.start_position, { x: 0.7, y: 0.5 })
  assert.deepEqual(gesture.end_position, { x: 0.3, y: 0.5 })
  assert.equal(gesture.movement_direction, 'left')
})

test('petting follows relative displacement with bounded head and gaze values', () => {
  const touch = new TouchAttention()
  touch.begin(150, 160, 300, 360, 0)
  touch.move(190, 190, 250)
  const value = touch.sample(250, 0.1)
  assert.ok(value.pose.yaw > 0 && value.pose.pitch > 0)
  assert.ok(value.pose.gazeX > 0 && value.pose.gazeY < 0)
  assert.ok(value.weights.eyeLookOutLeft > 0 && value.weights.eyeLookInRight > 0)
  assert.ok(value.weights.eyeLookDownLeft > 0 && value.weights.eyeLookDownRight > 0)
  assert.ok(value.weights.mouthSmileLeft > 0)
  touch.move(100000, 100000, 300)
  const bounded = touch.sample(300, 0.1)
  for (const key of ['pitch', 'yaw', 'roll', 'gazeX', 'gazeY']) assert.ok(Math.abs(bounded.pose[key]) <= 1)
})

test('a stationary press and a short click do not count as stroking', () => {
  const touch = new TouchAttention()
  touch.begin(150, 180, 300, 360, 0)
  touch.move(152, 180, 1000)
  assert.equal(touch.sample(1000, 0.1).weights.mouthSmileLeft, 0)
  touch.begin(150, 180, 300, 360, 1100)
  touch.move(180, 180, 1150)
  assert.equal(touch.sample(1150, 0.1).weights.mouthSmileLeft, 0)
})

test('release returns smoothly to neutral and does not retain the old gesture', () => {
  const touch = new TouchAttention()
  touch.begin(150, 180, 300, 360, 0)
  touch.move(180, 180, 250)
  const held = touch.sample(250, 0.1)
  touch.end()
  const released = touch.sample(266, 0.016)
  assert.ok(released.pose.yaw > 0 && released.pose.yaw < held.pose.yaw)
  for (let time = 300; time < 2000; time += 32) touch.sample(time, 0.032)
  assert.equal(touch.sample(2000, 0.032), null)
  touch.begin(150, 180, 300, 360, 2100)
  assert.equal(touch.sample(2100, 0.016).weights.mouthSmileLeft, 0)
})

test('invalid coordinates and abandoned presses cannot leave a pose running', () => {
  const touch = new TouchAttention()
  assert.equal(touch.begin(NaN, 180, 300, 360, 0), false)
  assert.equal(touch.begin(150, 180, 0, 360, 0), false)
  assert.equal(touch.sample(0, 0.016), null)
  touch.begin(150, 180, 300, 360, 0)
  touch.move(180, 180, 250)
  touch.sample(250, 0.1)
  for (let time = 11000; time < 12000; time += 32) touch.sample(time, 0.032)
  assert.equal(touch.sample(12000, 0.032), null)
})
