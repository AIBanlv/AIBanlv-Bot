import assert from 'node:assert/strict'
import path from 'node:path'
import { createRequire } from 'node:module'
import { waitForDeviceState } from './device-state-fixture.mjs'

export async function verifyModelTest({ page, app }) {
  await page.locator('#binding-tab-keys').click()
  await page.locator('#deepseek-test').click()
  await page.waitForFunction(() => !document.querySelector('#model-form button[type="submit"]').disabled)
  assert.match(await page.locator('#model-feedback').textContent(), /填写自己的 DeepSeek API Key/)
  await page.locator('#model-deepseek').fill('fixture-own-deepseek')
  await page.locator('#deepseek-test').click()
  await page.waitForFunction(() => !document.querySelector('#model-form button[type="submit"]').disabled)
  assert.match(await page.locator('#model-feedback').textContent(), /DeepSeek 连接正常/)
  assert.equal(await page.locator('#model-deepseek').inputValue(), 'fixture-own-deepseek')
  assert.equal((await page.evaluate(() => window.controlDevice.assistantState())).configured, false)
  await app.evaluate(() => { globalThis.fixtureRejectText = true })
  await page.locator('#deepseek-test').click()
  await page.waitForFunction(() => !document.querySelector('#model-form button[type="submit"]').disabled)
  assert.match(await page.locator('#model-feedback').textContent(), /DeepSeek 文字回复失败/)
  assert.equal(await page.locator('#model-deepseek').inputValue(), 'fixture-own-deepseek')
  await app.evaluate(() => { globalThis.fixtureRejectText = false })
  await page.evaluate(() => window.controlDevice.configureAssistant({ apiKey: 'fixture-own-deepseek', enabled: false, remember: false }))
  await page.locator('#model-deepseek').fill('')
  await page.locator('#deepseek-test').click()
  await page.waitForFunction(() => !document.querySelector('#model-form button[type="submit"]').disabled)
  assert.match(await page.locator('#model-feedback').textContent(), /DeepSeek 连接正常/)
  assert.equal((await page.evaluate(() => window.controlDevice.assistantState())).enabled, false)
  await page.locator('#realtime-test').click()
  await page.waitForFunction(() => !document.querySelector('#model-form button[type="submit"]').disabled)
  assert.match(await page.locator('#model-feedback').textContent(), /请填写.*Realtime Key/)
  await page.locator('#realtime-key').fill('fixture-own-realtime')
  await page.locator('#realtime-test').click()
  await page.waitForFunction(() => !document.querySelector('#model-form button[type="submit"]').disabled)
  assert.match(await page.locator('#model-feedback').textContent(), /请填写业务空间/)
  await page.locator('#model-workspaceId').fill('fixture-space')
  await page.locator('#model-voice').fill('longanlingxi')
  await page.locator('#realtime-test').click()
  await page.waitForFunction(() => !document.querySelector('#model-form button[type="submit"]').disabled)
  assert.match(await page.locator('#model-feedback').textContent(), /Realtime 连接正常/)
  assert.equal(await page.locator('#realtime-key').inputValue(), 'fixture-own-realtime')
  assert.equal(await page.locator('#model-voice').inputValue(), 'longanlingxi')
  const saved = await page.evaluate(() => window.controlDevice.modelState())
  assert.equal(saved.configured, false)
  assert.equal(saved.workspaceId, '')
  console.log('model tests Electron: DeepSeek/Realtime draft Keys, saved-Key fallback, retained inputs, no automatic persistence or Harness activation passed')
}

export async function verifyModelPage({ page, pet, app, root, artifacts, AxeBuilder }) {
  await waitForDeviceState(pet, value => value.models.platformEnabled && value.connection === 'connected')
  await page.locator('.settings-nav[data-section="binding"]').click()
  await page.locator('#binding-tab-scan').click()
  await page.locator('#qr').waitFor({ state: 'visible', timeout: 5000 })
  assert.equal(await page.locator('#binding-platform').count(), 0)
  assert.equal((await pet.evaluate(() => window.controlDevice.state())).models.platformEnabled, true,
    'opening settings reconnects even when the removed toggle was previously saved off')
  await page.waitForFunction(() => document.querySelector('#qr').naturalWidth > 0)
  const require = createRequire(import.meta.url)
  const jsQR = require(path.resolve(root, '../../../.codex_tmp/device-qa/node_modules/jsqr'))
  const { PNG } = require(path.resolve(root, '../../../.codex_tmp/device-qa/node_modules/pngjs'))
  const png = PNG.sync.read(Buffer.from((await page.locator('#qr').getAttribute('src')).split(',')[1], 'base64'))
  const decoded = jsQR(new Uint8ClampedArray(png.data), png.width, png.height)
  assert.ok(decoded, 'the login image must be a scannable QR code')
  assert.equal(new URL(decoded.data).searchParams.get('deviceCode'), (await pet.evaluate(() => window.controlDevice.state())).deviceId)
  assert.equal(await page.locator('[data-settings-page="binding"] #model-form').count(), 1)
  assert.equal(await page.locator('#model-form').isVisible(), false)
  assert.equal(await page.locator('.settings-nav[data-section="model-settings"]').count(), 0)
  await page.screenshot({ path: path.join(artifacts, 'binding-only.png') })

  await page.locator('#binding-tab-scan').focus()
  await page.keyboard.press('ArrowRight')
  assert.equal(await page.locator('#binding-tab-keys').getAttribute('aria-selected'), 'true')
  assert.equal(await page.locator('h1').textContent(), '设备绑定')
  assert.equal(await page.locator('#model-source').count(), 0)
  for (const id of ['model-deepseek', 'realtime-key', 'model-workspaceId']) assert.equal(await page.locator(`#${id}`).isVisible(), true)
  assert.match(await page.locator('#model-current').textContent(), /线上角色.*平台积分/)
  assert.equal(await page.locator('#model-model').inputValue(), 'qwen-audio-3.0-realtime-flash')
  assert.equal(await page.locator('#model-voice').inputValue(), 'longanlingxi')
  assert.equal(await page.locator('#qr').isVisible(), false)
  await page.locator('#model-deepseek').fill('unsaved-local-key')
  await page.locator('#binding-tab-scan').click()
  await page.locator('#qr').waitFor({ state: 'visible' })
  await page.evaluate(() => window.controlDevice.configureModels({ platformEnabled: false }))
  await waitForDeviceState(page, value => !value.models.platformEnabled)
  await page.locator('#binding-refresh').click()
  await page.locator('#qr').waitFor({ state: 'visible' })
  assert.equal((await pet.evaluate(() => window.controlDevice.state())).models.source, 'auto')
  await page.locator('#binding-tab-keys').click()
  assert.equal(await page.locator('#model-deepseek').inputValue(), 'unsaved-local-key', 'navigation preserves unsaved model fields')
  await page.locator('#model-deepseek').fill('')
  for (const width of [320, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  }
  assert.deepEqual((await new AxeBuilder({ page }).setLegacyMode().analyze()).violations, [])
  await page.screenshot({ path: path.join(artifacts, 'model-settings.png') })
  assert.equal((await app.evaluate(() => globalThis.fixtureRequests)).some(row => /desktop\/(sessions|account)$/.test(row.url)), false)
  console.log('model page Electron: binding tabs, keyboard, QR refresh, draft preservation, role billing, defaults and responsive/axe passed')
}
