import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import path from 'node:path'

export async function verifySourceUpdate({ page, electron, root, artifacts, applicationVersion }) {
  await page.waitForFunction(() => document.querySelector('#account-update').textContent === '检查更新')
  await page.locator('#account-menu > summary').click()
  await page.locator('#account-update').click()
  const dialog = page.locator('#desktop-update-dialog')
  assert.equal(await page.locator('#desktop-update-title').textContent(), '源码更新')
  assert.equal(await page.locator('#desktop-update-source').isVisible(), true)
  assert.match(await page.locator('#desktop-update-version').textContent(), new RegExp(applicationVersion.replaceAll('.', '\\.')))
  await page.waitForFunction(() => document.querySelector('#desktop-update-status').textContent.includes('已包含上游'))
  const state = await page.evaluate(() => window.controlDevice.updateState())
  assert.equal(state.runMode, 'source')
  assert.equal(state.source.branch, 'master')
  assert.match(await page.locator('#desktop-update-revision').textContent(), new RegExp(state.source.commit.slice(0, 12)))
  assert.equal(await page.locator('#desktop-update-check').isVisible(), true)
  assert.equal(await page.locator('#desktop-update-install').isVisible(), false)
  assert.equal((await page.evaluate(() => window.controlDevice.downloadUpdate())).ok, false)
  await electron.evaluate(async () => { await globalThis.sourceFixture.publish() })
  await page.locator('#desktop-update-check').click()
  await page.waitForFunction(() => !document.querySelector('#desktop-update-install').hidden)
  assert.equal(await page.locator('#desktop-update-install').textContent(), '更新并重启')
  assert.match(await page.locator('#desktop-update-source-status').textContent(), /无需重新安装依赖/)
  assert.deepEqual(await electron.evaluate(() => globalThis.updateFixture.updateRequests), [])
  for (const width of [320, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 800 })
    const bounds = await dialog.boundingBox()
    assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= width)
    assert.equal(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth), true)
    await page.screenshot({ path: path.join(artifacts, `source-${width}.png`) })
  }
  await page.evaluate(await readFile(path.resolve(root, '../../../.codex_tmp/web-pet-qa/node_modules/axe-core/axe.min.js'), 'utf8'))
  const violations = await page.evaluate(async () => (await window.axe.run(document.querySelector('#desktop-update-dialog'),
    { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa'] } })).violations)
  assert.deepEqual(violations, [])
  await page.keyboard.press('Tab')
  assert.equal(await dialog.evaluate(element => element.contains(document.activeElement)), true)
  await page.keyboard.press('Escape')
  assert.equal(await dialog.isVisible(), false)
  await page.waitForFunction(() => document.activeElement === document.querySelector('#account-menu > summary'))
  await page.locator('#account-menu > summary').click()
  await page.locator('#account-update').click()
  await page.waitForFunction(() => !document.querySelector('#desktop-update-install').hidden)
  await electron.evaluate(() => { globalThis.updateFixture.mode = 'stall' })
  await page.locator('#desktop-update-check').click()
  await page.waitForFunction(() => !document.querySelector('#desktop-update-cancel').hidden)
  await page.locator('#desktop-update-cancel').click()
  await page.waitForFunction(() => document.querySelector('#desktop-update-status').textContent.includes('取消'))
  await electron.evaluate(async () => {
    globalThis.updateFixture.mode = 'normal'
    await globalThis.sourceFixture.writeApp('user edits')
  })
  await page.locator('#desktop-update-check').click()
  await page.waitForFunction(() => document.querySelector('#desktop-update-status').textContent.includes('未提交'))
  assert.equal(await page.locator('#desktop-update-install').isVisible(), false)
  await electron.evaluate(async () => {
    await globalThis.sourceFixture.writeApp('old')
    globalThis.updateFixture.mode = 'handoff-error'
  })
  await page.locator('#desktop-update-check').click()
  await page.waitForFunction(() => !document.querySelector('#desktop-update-install').hidden)
  await page.locator('#desktop-update-install').click()
  await page.waitForFunction(() => document.querySelector('#desktop-update-status').textContent.includes('Node.js 24'))
  assert.equal(await electron.evaluate(() => Boolean(globalThis.updateFixture.sourceQuit)), false)
  const pet = electron.windows().find(page => page.url().endsWith('/device/device-pet.html'))
  assert.equal((await pet.evaluate(() => window.controlDevice.installUpdate())).ok, false)
  await electron.evaluate(() => { globalThis.updateFixture.mode = 'normal' })
  await page.locator('#desktop-update-install').click()
  await page.waitForFunction(() => document.querySelector('#desktop-update-status').textContent.includes('即将退出'))
  assert.equal(await electron.evaluate(() => globalThis.updateFixture.sourceQuit), true)
  assert.deepEqual(await electron.evaluate(() => globalThis.updateFixture.updateRequests), [])
  console.log('source update Electron: real Git check, current/available/dirty/cancel/retry/handoff, no installer requests, pet denied, keyboard, four widths and axe passed')
}
